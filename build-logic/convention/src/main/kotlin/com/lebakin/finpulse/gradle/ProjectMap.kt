package com.lebakin.finpulse.gradle

/**
 * Renders docs/project-map.md from the Gradle project graph and module cards.
 *
 * External libraries are omitted. Test configurations never reach this renderer:
 * the module-graph plugin records only production dependencies.
 */
object ProjectMap {
    fun render(
        modules: List<MappedModule>,
        edges: List<ModuleEdge>,
        cards: Map<String, String>,
    ): String {
        val sortedModules = modules.sortedWith(
            compareBy<MappedModule> { it.gradlePath == null }
                .thenBy { it.gradlePath ?: "" }
                .thenBy { it.directory },
        )
        val projectEdges = edges
            .filter { it.toProject != null }
            .distinct()
            .sortedWith(compareBy({ it.from }, { it.configuration }, { it.toProject }))
        val cardPaths = sortedModules.map { it.cardPath }.distinct()

        return buildString {
            appendLine("# Project map")
            appendLine()
            appendLine(
                "Generated by `./gradlew projectMap` from the Gradle graph and module `AGENTS.md` cards. " +
                    "Do not edit this file. `./gradlew checkProjectMap` fails when it does not match the repository.",
            )
            appendLine()
            appendLine("## Modules")
            appendLine()
            appendLine("| Gradle path | Directory | Card |")
            appendLine("| --- | --- | --- |")
            sortedModules.forEach { module ->
                val path = module.gradlePath ?: "—"
                appendLine("| `$path` | `${module.directory}` | `${module.cardPath}` |")
            }
            appendLine()
            appendLine("## Dependencies")
            appendLine()
            appendLine("Production project dependencies. Test configurations are omitted.")
            appendLine()
            appendLine("| From | Configuration | To |")
            appendLine("| --- | --- | --- |")
            projectEdges.forEach { edge ->
                appendLine("| `${edge.from}` | `${edge.configuration}` | `${edge.toProject}` |")
            }
            appendLine()
            appendLine("## Cards")
            cardPaths.forEach { path ->
                val body = cards[path]?.trimEnd()
                    ?: error("Missing card text for $path")
                appendLine()
                appendLine("### `$path`")
                appendLine()
                append(body)
                append('\n')
            }
        }
    }
}

data class MappedModule(
    val gradlePath: String?,
    val directory: String,
    val cardPath: String,
)
