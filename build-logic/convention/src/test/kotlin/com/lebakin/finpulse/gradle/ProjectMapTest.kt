package com.lebakin.finpulse.gradle

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse

class ProjectMapTest {
    @Test
    fun rendersModulesGraphAndCards() {
        val text = ProjectMap.render(
            modules = listOf(
                MappedModule(":core:mvi", "core/mvi", "core/mvi/AGENTS.md"),
                MappedModule(":core:common", "core/common", "core/common/AGENTS.md"),
                MappedModule(null, "iosApp", "iosApp/AGENTS.md"),
                MappedModule(":catalog:android", "catalog/android", "catalog/AGENTS.md"),
                MappedModule(":catalog:catalogShared", "catalog/shared", "catalog/AGENTS.md"),
            ),
            edges = listOf(
                ModuleEdge(":core:mvi", "commonMainImplementation", ":core:common", null, null),
                ModuleEdge(":catalog:android", "implementation", ":catalog:catalogShared", null, null),
                ModuleEdge(":core:navigation", "commonMainApi", null, "org.jetbrains.androidx.navigation3", "navigation3-ui"),
                ModuleEdge(":core:mvi", "commonMainImplementation", ":core:common", null, null),
            ),
            cards = mapOf(
                "catalog/AGENTS.md" to "# :catalog\n\nShared card.\n",
                "core/common/AGENTS.md" to "# :core:common\n",
                "core/mvi/AGENTS.md" to "# :core:mvi\n",
                "iosApp/AGENTS.md" to "# iosApp\n",
            ),
        )

        assertEquals(
            """
            # Project map

            Generated by `./gradlew projectMap` from the Gradle graph and module `AGENTS.md` cards. Do not edit this file. `./gradlew checkProjectMap` fails when it does not match the repository.

            ## Modules

            | Gradle path | Directory | Card |
            | --- | --- | --- |
            | `:catalog:android` | `catalog/android` | `catalog/AGENTS.md` |
            | `:catalog:catalogShared` | `catalog/shared` | `catalog/AGENTS.md` |
            | `:core:common` | `core/common` | `core/common/AGENTS.md` |
            | `:core:mvi` | `core/mvi` | `core/mvi/AGENTS.md` |
            | `—` | `iosApp` | `iosApp/AGENTS.md` |

            ## Dependencies

            Production project dependencies. Test configurations are omitted.

            | From | Configuration | To |
            | --- | --- | --- |
            | `:catalog:android` | `implementation` | `:catalog:catalogShared` |
            | `:core:mvi` | `commonMainImplementation` | `:core:common` |

            ## Cards

            ### `catalog/AGENTS.md`

            # :catalog

            Shared card.

            ### `core/common/AGENTS.md`

            # :core:common

            ### `core/mvi/AGENTS.md`

            # :core:mvi

            ### `iosApp/AGENTS.md`

            # iosApp
            """.trimIndent() + "\n",
            text,
        )
        assertFalse(text.contains("navigation3-ui"))
    }
}
